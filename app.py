# 6️⃣ Batch runner: process everything under images/
#    (will mimic your VS Code flow: for each defect class folder)
# ==========================================
def process_images_folder(images_folder):
    for defect_type in os.listdir(images_folder):
        defect_type_path = os.path.join(images_folder, defect_type)
        if not os.path.isdir(defect_type_path):
            continue

        for fname in os.listdir(defect_type_path):
            if not fname.lower().endswith(('.jpg', '.jpeg', '.png')):
                continue
            img_path = os.path.join(defect_type_path, fname)
            try:
                process_single_image(img_path)
            except Exception as e:
                print(f"❌ Skipping {img_path}: {e}")


